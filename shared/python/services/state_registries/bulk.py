"""Bulk-file adapter — CSV / TSV / fixed-width, optionally inside a ZIP.

Several states publish the whole registry as one downloadable file instead of an
API. Those files are large (hundreds of MB, some over a GB uncompressed), so the
adapter never loads one into memory: it streams the download to a temp file,
then streams rows out of it.

Encoding
--------
These exports are generated by decades-old mainframe pipelines and are routinely
not UTF-8 — latin-1 and cp1252 bytes appear inside otherwise-ASCII files. We
decode with `errors="replace"` rather than guessing a codec, because one bad
byte must not abort a 2M-row import; a mangled character in one company name is
recoverable, a failed run is not.
"""
from __future__ import annotations

import csv
import io
import logging
import os
import tempfile
import zipfile
from typing import Any, Dict, Iterator, Optional

from .base import METHOD_BULK, CompanyRecord, StateAdapter

logger = logging.getLogger(__name__)

_TIMEOUT = 120
_CHUNK = 1 << 20
#: Refuse absurd downloads rather than filling the disk on a redirect to a
#: surprise archive. Real state exports top out well under this.
_MAX_BYTES = 4 << 30

csv.field_size_limit(10 * 1024 * 1024)


class BulkFileAdapter(StateAdapter):
    method = METHOD_BULK

    def __init__(self, *, state: str, name: str, url: str,
                 fields: Dict[str, str], portal_url: str = "",
                 record_estimate: int = 0, delimiter: str = ",",
                 member: str = "", encoding: str = "utf-8",
                 notes: str = "") -> None:
        self.state = state.upper()
        self.name = name
        self.source_url = url
        self.portal_url = portal_url
        self.record_estimate = record_estimate
        self.fields = fields
        self.delimiter = delimiter
        #: Filename (or suffix) to read when the download is a ZIP.
        self.member = member
        self.encoding = encoding
        self.notes = notes

    # -- fetching ------------------------------------------------------------

    def _download(self) -> str:
        import requests
        logger.info("%s: downloading %s", self.state, self.source_url[:110])
        fd, path = tempfile.mkstemp(prefix=f"registry-{self.state}-")
        os.close(fd)
        total = 0
        with requests.get(self.source_url, stream=True, timeout=_TIMEOUT,
                          headers={"User-Agent": "JobPilot/1.0 (+employer-coverage)"}
                          ) as resp:
            resp.raise_for_status()
            with open(path, "wb") as fh:
                for chunk in resp.iter_content(_CHUNK):
                    if not chunk:
                        continue
                    total += len(chunk)
                    if total > _MAX_BYTES:
                        raise RuntimeError(f"{self.state}: download exceeded cap")
                    fh.write(chunk)
        logger.info("%s: downloaded %.1f MB", self.state, total / 1e6)
        return path

    def _open_rows(self, path: str) -> Iterator[Dict[str, Any]]:
        if zipfile.is_zipfile(path):
            with zipfile.ZipFile(path) as zf:
                names = [n for n in zf.namelist() if not n.endswith("/")]
                if self.member:
                    names = [n for n in names
                             if n == self.member or n.endswith(self.member)] or names
                if not names:
                    return
                with zf.open(names[0]) as raw:
                    stream = io.TextIOWrapper(raw, encoding=self.encoding,
                                              errors="replace", newline="")
                    yield from csv.DictReader(stream, delimiter=self.delimiter)
            return
        with open(path, "r", encoding=self.encoding, errors="replace",
                  newline="") as fh:
            yield from csv.DictReader(fh, delimiter=self.delimiter)

    def _iter_raw(self, *, cursor: Optional[str]) -> Iterator[Dict[str, Any]]:
        try:
            skip = max(0, int(cursor or 0))
        except (TypeError, ValueError):
            skip = 0
        path = self._download()
        try:
            for i, row in enumerate(self._open_rows(path)):
                if i < skip:
                    continue
                row["__cursor__"] = str(i)
                yield row
        finally:
            try:
                os.unlink(path)
            except OSError:
                pass

    # -- mapping -------------------------------------------------------------

    def _pick(self, raw: Dict[str, Any], key: str) -> str:
        col = self.fields.get(key)
        if not col:
            return ""
        value = raw.get(col)
        if value is None:
            # Bulk exports have inconsistent header casing and stray whitespace
            # far more often than API responses do.
            target = col.strip().lower()
            for k, v in raw.items():
                if k and k.strip().lower() == target:
                    value = v
                    break
        return "" if value is None else str(value).strip()

    def _to_record(self, raw: Dict[str, Any]) -> Optional[CompanyRecord]:
        name = self._pick(raw, "name")
        if not name:
            return None
        return CompanyRecord(
            name=name,
            state=self.state,
            entity_type=self._pick(raw, "type"),
            status=self._pick(raw, "status"),
            registered_on=self._pick(raw, "registered")[:10],
            city=self._pick(raw, "city"),
            postal=self._pick(raw, "postal"),
            registry_id=self._pick(raw, "registry_id"),
            source=f"bulk:{self.state}",
            raw={"cursor": raw.get("__cursor__", "")},
        )
