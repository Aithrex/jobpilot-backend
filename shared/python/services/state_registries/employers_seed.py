def records_for(state: str):
    """Yield dicts suitable for FederalProxyAdapter._to_record."""
    code = (state or "").strip().upper()
    for name, domain in SEED.get(code, ()):
        yield {"name": name, "domain": domain, "state": code,
               "source": "federal-seed", "signals": {"known_domain": True}}
