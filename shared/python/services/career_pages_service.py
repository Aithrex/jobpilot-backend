def run_career_pages_search(
    payload: Dict[str, Any],
    partial_cb: Optional[Callable[[Dict[str, Any]], None]] = None,
) -> Dict[str, Any]:
    """Execute one Career Pages search (async job runner entry).

    payload mirrors the Workday tab: titles, industries, companies (slugs),
    location (unused server-side beyond US filter), remote_only, us_only,
    force_refresh, user_email.
    """
    titles = [str(t).strip() for t in (payload.get("titles") or []) if str(t or "").strip()]
    industries = {str(i).strip() for i in (payload.get("industries") or []) if str(i or "").strip()}
    companies = {str(x).strip().lower() for x in (payload.get("companies") or []) if str(x or "").strip()}
    remote_only = bool(payload.get("remote_only", False))
    us_only = bool(payload.get("us_only", True))
    force_refresh = bool(payload.get("force_refresh", False))
    user_email = str(payload.get("user_email") or "")
    # Viewer timezone (recency in the USER's calendar day) + optional tighter
    # fan-out budget for embedded callers (guest scan). See workday service.
    tz_offset = _clamp_tz_offset(payload.get("tz_offset_minutes"))
    try:
        overall_timeout = min(OVERALL_TIMEOUT, max(30, int(payload.get("overall_timeout") or OVERALL_TIMEOUT)))
    except (TypeError, ValueError):
        overall_timeout = OVERALL_TIMEOUT
    # Detail-enrichment cap for embedded callers (guest scan) — shrink only.
    try:
        _enrich_cap = int(payload.get("enrich_top")) if payload.get("enrich_top") else None
    except (TypeError, ValueError):
        _enrich_cap = None
    enrich_top_n = min(DETAIL_ENRICH_TOP, _enrich_cap) if _enrich_cap else DETAIL_ENRICH_TOP
    enrich_recent_n = min(DETAIL_ENRICH_RECENT, _enrich_cap) if _enrich_cap else DETAIL_ENRICH_RECENT

    rows = [
        r for r in list(CAREER_PAGES_CATALOG) + ENTERPRISE_CATALOG
        if (r["ats"] in FETCHERS or r["ats"] in ENTERPRISE_FETCHERS)
        and (not industries or r.get("industry") in industries)
        and (not companies or r["slug"].lower() in companies)
    ]
    skills, resume_years = _load_resume_profile(user_email)
    # Anonymous callers (guest scan) pass parsed skills/years directly so
    # scoring quality matches an authed run. Never overrides a real profile.
    if not user_email:
        payload_skills = [str(s).strip() for s in (payload.get("resume_skills") or []) if str(s or "").strip()]
        if payload_skills:
            skills = payload_skills[:60]
        try:
            if payload.get("resume_years") is not None:
                resume_years = max(0, int(payload["resume_years"]))
        except (TypeError, ValueError):
            pass
    title_terms = _derive_query_terms(titles, cap=MAX_QUERY_TERMS)
    # Widen tier-1 recall to the user's OWN profession (a nurse also keeps
    # "Charge Nurse"; a SWE is unchanged — this unions with the engineering net).
    role_noun_re = user_role_noun_re(titles)
    skill_terms = _derive_skill_terms(skills, title_terms,
                                      cap=TOTAL_TERMS_CAP - len(title_terms))
    terms = title_terms + skill_terms
    term_res = [re.compile(re.escape(t), re.IGNORECASE) for t in title_terms]
    # Broaden title matching: individual role tokens too ("devops engineer"
    # must keep "Senior DevOps & Platform Engineer").
    for t in title_terms:
        toks = [w for w in t.split() if len(w) > 3]
        if len(toks) >= 2:
            term_res.append(re.compile(
                r".*".join(re.escape(w) for w in toks), re.IGNORECASE))
    skill_res = [rx for rx in (_build_match_regex(s) for s in skills[:30]) if rx]

    errors: List[str] = []
    coll = _get_cache_collection()
    key = _cache_key(rows, terms, us_only)
    cache_hit = False
    raw_jobs: Optional[List[Dict[str, Any]]] = None
    if not force_refresh:
        raw_jobs = _read_cache(coll, key)
        cache_hit = raw_jobs is not None

    companies_total = len(rows)
    companies_done = 0
    companies_with_results = 0
    diagnostics = {"task_errors": 0}

    if raw_jobs is None:
        collected: List[Dict[str, Any]] = []
        done = 0
        hits: set = set()
        matchers = _role_matchers(titles)
        stream_rx = [(s, _build_match_regex(s)) for s in skills[:30]]
        prov_cache: Dict[str, Tuple[int, List[str]]] = {}

        def _provisional(j: Dict[str, Any]) -> Tuple[int, List[str]]:
            cached = prov_cache.get(j["job_id"])
            if cached is None:
                blob = (j["title"] + "\n" + (j.get("description") or "")[:1500]
                        + "\n" + (j.get("_meta") or "")).lower()
                tl = j["title"].lower()
                tm = any(all(tok in tl for tok in m) for m in matchers)
                matched = [s for s, rx in stream_rx if rx is not None and rx.search(blob)]
                score = min(100, min(55, len(matched) * 6) + (45 if tm else (20 if matched else 0)))
                if not skills and not tm:
                    score = 15
                cached = (score, matched[:8])
                prov_cache[j["job_id"]] = cached
            return cached

        def _snapshot() -> None:
            if not partial_cb:
                return
            rows_snap = list({j["job_id"]: j for j in collected}.values())
            for j in rows_snap:
                sc, mt = _provisional(j)
                j["match_score"] = sc
                j["matched_skills"] = mt
                j.setdefault("missing_skills", [])
            rows_snap.sort(key=lambda x: (
                -x["match_score"],
                x.get("days_ago") if x.get("days_ago") is not None else 99))
            try:
                partial_cb({
                    "progress": {"tenants_done": done,
                                 "tenants_total": companies_total,
                                 "jobs_found": len(rows_snap)},
                    "jobs": [
                        {k: v for k, v in j.items() if k not in ("description", "_meta", "_exp", "_fam_counts")}
                        for j in rows_snap[:STREAM_TOP]
                    ],
                    "total": len(rows_snap),
                    "streaming": True,
                })
            except Exception:
                pass

        def _one_company(c: Dict[str, str]) -> Tuple[List[Dict[str, Any]], Optional[str]]:
            try:
                if c["ats"] in ENTERPRISE_FETCHERS:
                    # Search-style platforms take the query terms directly.
                    jobs_c = ENTERPRISE_FETCHERS[c["ats"]](c, title_terms)
                    # Same posting often matches several terms — dedupe here.
                    jobs_c = list({j["job_id"]: j for j in jobs_c}.values())
                else:
                    jobs_c = FETCHERS[c["ats"]](c)
            except Exception as e:
                return [], f"{c['slug']}: {type(e).__name__}"
            jobs_c = [j for j in jobs_c
                      if j.get("days_ago") is not None and j["days_ago"] <= WINDOW_DAYS]
            if us_only:
                jobs_c = [j for j in jobs_c if _keep_us(j)]
            jobs_c = _keep_relevant(jobs_c, term_res, skill_res, role_noun_re)
            jobs_c.sort(key=lambda j: (j.get("_tier", 1), j.get("days_ago") or 0))
            jobs_c = jobs_c[:PER_COMPANY_KEEP]
            for j in jobs_c:
                j.pop("_tier", None)
            return jobs_c, None

        with ThreadPoolExecutor(max_workers=MAX_WORKERS) as pool:
            futures = {pool.submit(_one_company, c): c for c in rows}
            try:
                for fut in as_completed(futures, timeout=overall_timeout):
                    c = futures[fut]
                    done += 1
                    try:
                        items, err = fut.result()
                    except Exception as e:  # pragma: no cover
                        items, err = [], str(e)
                    if err:
                        diagnostics["task_errors"] += 1
                    if items:
                        hits.add(c["slug"])
                        collected.extend(items)
                    if partial_cb and done % STREAM_EVERY_TASKS == 0:
                        _snapshot()
            except TimeoutError:
                pending = sum(1 for f in futures if not f.done())
                errors.append(f"timeout: {pending} companies did not finish")
                for f in futures:
                    if not f.done():
                        f.cancel()
        companies_done = done
        companies_with_results = len(hits)
        raw_jobs = list({j["job_id"]: j for j in collected}.values())
        _write_cache(coll, key, raw_jobs)
    else:
        companies_done = companies_total
        companies_with_results = len({j.get("tenant") for j in raw_jobs})

    # Serve path: recompute recency IN THE VIEWER'S TIMEZONE, apply window +
    # remote filters.
    jobs = []
    for j0 in raw_jobs:
        j = dict(j0)
        days = _days_ago(j.get("date_posted") or "", tz_offset)
        if days is None or days > WINDOW_DAYS:
            continue
        j["days_ago"] = days
        j["posted_text"] = _posted_text(days)
        jobs.append(j)
    if remote_only:
        jobs = [j for j in jobs if j.get("is_remote")]

    def _rank(items: List[Dict[str, Any]]) -> None:
        items.sort(key=lambda j: (
            -(j.get("match_score") or 0),
            j.get("days_ago") if j.get("days_ago") is not None else 99))

    jobs = _score_jobs(jobs, titles, skills, skill_terms, resume_years)
    _rank(jobs)

    if partial_cb:
        try:
            partial_cb({
                "progress": {"tenants_done": companies_total,
                             "tenants_total": companies_total,
                             "jobs_found": len(jobs), "phase": "details"},
                "jobs": [{k: v for k, v in j.items() if k not in ("description", "_meta", "_exp", "_fam_counts")}
                         for j in jobs[:STREAM_TOP]],
                "total": len(jobs), "streaming": True,
            })
        except Exception:
            pass

    top = jobs[:enrich_top_n] + [
        j for j in jobs[enrich_top_n:]
        if (j.get("days_ago") if j.get("days_ago") is not None else 99) <= 3
    ][:enrich_recent_n]
    if _enrich_details(top):
        _score_jobs(top, titles, skills, skill_terms, resume_years)
        _rank(jobs)
        if coll is not None:
            by_id = {j["job_id"]: j for j in top if j.get("description")}
            for rj in raw_jobs:
                e = by_id.get(rj["job_id"])
                if e is not None:
                    rj["description"] = e["description"]
            _write_cache(coll, key, raw_jobs)

    jobs = jobs[:GLOBAL_KEEP]
    _attach_feasibility(jobs, skills, resume_years)
    _rank(jobs)
    _attach_sponsorship(jobs)
    _apply_career_sponsorship(jobs)
    _drain_pools()
    for j in jobs:  # scoring-only signals — never exposed to the client
        j.pop("_meta", None)
        j.pop("_exp", None)
        j.pop("_fam_counts", None)

    window_counts = {"today": 0, "d1": 0, "d3": 0, "d7": 0, "d30": 0}
    for j in jobs:
        d = j.get("days_ago")
        if d is None:
            continue
        if d == 0:
            window_counts["today"] += 1
        if d <= 1:
            window_counts["d1"] += 1
        if d <= 3:
            window_counts["d3"] += 1
        if d <= 7:
            window_counts["d7"] += 1
        if d <= 30:
            window_counts["d30"] += 1

    return {
        "ok": True,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "jobs": jobs,
        "total": len(jobs),
        "window_counts": window_counts,
        "query_terms": terms,
        "tenants_total": companies_total,
        "tenants_done": companies_done,
        "tenants_with_results": companies_with_results,
        "industries_available": INDUSTRIES,
        "ats_available": ATS_KINDS,
        "cache_hit": cache_hit,
        "us_only": us_only,
        "resume_skill_count": len(skills),
        "diagnostics": diagnostics,
        "errors": errors[:20],
    }


def catalog_summary() -> Dict[str, Any]:
    all_rows = list(CAREER_PAGES_CATALOG) + ENTERPRISE_CATALOG
    by_ind: Dict[str, List[Dict[str, str]]] = {}
    for r in all_rows:
        by_ind.setdefault(r["industry"], []).append(r)
    return {
        "total": len(all_rows),
        "industries": [
            {"key": k, "count": len(v),
             "companies": [{"name": r["display_name"], "tenant": r["slug"],
                            "ats": r["ats"]} for r in
                           sorted(v, key=lambda x: x["display_name"].lower())]}
            for k, v in sorted(by_ind.items())
        ],
    }
