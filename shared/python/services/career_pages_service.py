def _keep_us(job: Dict[str, Any], keep_ambiguous: bool = False) -> bool:
    """HARD US filter for board rows.

    DELEGATES to ``services.us_geo`` — the single implementation of this rule.
    This function used to carry its own tiered copy, which drifted from
    ``workday_jobs_service._geo_keep_us`` (no bare-"US" tier, no Toronto
    guard) while ``inventory_feed`` served BOTH source tabs through it. A live
    A/B over 20,000 active postings put the old rule at 43% kept with 33
    foreign leaks; the shared rule keeps 50% with the leaks gone. See
    ``us_geo`` for the decision order and the measured cases behind it.

    Signature and keep/drop contract are unchanged, so every existing caller
    and the ``_keep_us_lenient`` rollback below behave as before.
    """
    from services import us_geo

    return us_geo.keep_us_row(job, keep_ambiguous=keep_ambiguous)


def _keep_us_lenient(job: Dict[str, Any]) -> bool:
    """Lenient US keep-filter — the PRE-hardening contract: identical to
    ``_keep_us`` but KEEPS ambiguous rows ("N Locations", bare non-foreign
    city, unknown) instead of dropping them. Explicit foreign country/city is
    still dropped. This is the rollback the guest ``GUEST_US_STRICT=0`` path
    reverts to, kept separate so the board hard-filter above is unaffected."""
    return _keep_us(job, keep_ambiguous=True)


# ----------------------------------------------------------------------
# Relevance keep-filter (boards return EVERYTHING; Workday searched for us)
# ----------------------------------------------------------------------

# Role nouns worth keeping even without a full term match — boards return
# their ENTIRE openings list (Workday searched for us), so recall depends on
# this net. "Backend Engineer" / "Site Reliability Engineer" / "Infrastructure
# Engineer" must survive a "devops engineer, software developer" term set.
_ROLE_NOUN_RE = re.compile(
    r"engineer|developer|scientist|architect|devops|\bsre\b|programmer",
    re.IGNORECASE)


def _keep_relevant(jobs: List[Dict[str, Any]], term_res: List[re.Pattern],
                   skill_res: List[re.Pattern],
                   extra_role_re: Optional[re.Pattern] = None) -> List[Dict[str, Any]]:
    """Keep rows a Workday CXS search WOULD have retrieved, tiered:
      0 - a query term matches the title (best)
      1 - the title carries a role noun (the built-in engineering net UNION the
          user's own profession nouns via ``extra_role_re`` — so a nurse also
          recalls 'Charge Nurse' rows), or the description mentions >=2 distinct
          resume skills (the differently-titled-but-matching-skills recall path)
    The tier drives the per-company cap so term matches never lose their
    slot to generic engineer rows."""
    out = []
    for j in jobs:
        title = j["title"].lower()
        hits = [rx.pattern for rx in term_res if rx.search(title)]
        if hits:
            j["matched_terms"] = hits[:3]
            j["_tier"] = 0
            out.append(j)
            continue
        if _ROLE_NOUN_RE.search(title) or (extra_role_re and extra_role_re.search(title)):
            j["matched_terms"] = []
            j["_tier"] = 1
            out.append(j)
            continue
        # Include inline board metadata so a description-less row (SmartRecruiters
        # / Workable) can still be recalled by skills its department/function names.
        desc = ((j.get("description") or "") + " " + (j.get("_meta") or "")).lower()
        if desc.strip() and sum(1 for rx in skill_res if rx.search(desc)) >= 2:
            j["matched_terms"] = []
            j["_tier"] = 1
            out.append(j)
    return out


