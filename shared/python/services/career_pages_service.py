_MONTH_DATE_RE = re.compile(r"^[A-Za-z]+\s+\d{1,2},\s+\d{4}$")


def _us_month_to_iso(text: str) -> str:
    """'July  7, 2026' (Amazon double-space quirk included) -> ISO date."""
    t = re.sub(r"\s+", " ", str(text or "")).strip()
    if not _MONTH_DATE_RE.match(t):
        return ""
    try:
        return datetime.strptime(t, "%B %d, %Y").replace(
            tzinfo=timezone.utc).isoformat()
    except ValueError:
        return ""


def _epoch_to_iso(ts: Any) -> str:
    try:
        return datetime.fromtimestamp(int(ts), tz=timezone.utc).isoformat()
    except (TypeError, ValueError, OSError):
        return ""


def _fetch_amazon(c: Dict[str, str], terms: List[str]) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    for term in terms[:3]:
        r = _SESSION.get(
            "https://www.amazon.jobs/en/search.json",
            params={"base_query": term, "country": "USA", "result_limit": 50,
                    "offset": 0, "sort": "recent"},
            timeout=REQUEST_TIMEOUT)
        r.raise_for_status()
        for j in (r.json() or {}).get("jobs") or []:
            desc = " ".join(x for x in [
                j.get("description_short") or j.get("description") or "",
                j.get("basic_qualifications") or ""] if x)
            out.append(_row(
                c, j.get("id_icims") or j.get("id"), j.get("title") or "",
                f"https://www.amazon.jobs{j.get('job_path') or ''}",
                _us_month_to_iso(j.get("posted_date")),
                j.get("normalized_location") or j.get("location") or "",
                description=_html_to_text(desc)[:5000],
                country=str(j.get("country_code") or "")
                       .replace("USA", "us").lower()))
    return out


#: Eightfold returns TEN positions a page and ignores `num`.
#:
#: Measured live 2026-09-15 against Microsoft, Qualcomm and Netflix: `num=20`
#: and `num=50` both come back with ten, and `start` is a row offset that pages
#: cleanly (0/10/20/30 share no ids). This fetcher asked for 20, took the first
#: page and stopped, which is why one term returned at most twenty rows for
#: employers publishing 1,178 (Microsoft), 741 (Qualcomm) and 204 (Netflix).
#: The same arithmetic off by the same factor is what
#: `ats_providers.enterprise._EIGHTFOLD_POLICY` documents on the crawl side.
_EIGHTFOLD_PAGE = 10
#: Per TERM. Three terms x six pages is 180 rows, which is the right order for
#: an interactive tab that keeps 30 per company; the background crawl is where
#: a whole board gets read.
_EIGHTFOLD_PAGES_PER_TERM = 6


def _fetch_eightfold(c: Dict[str, str], terms: List[str]) -> List[Dict[str, Any]]:
    host = c["host"]
    domain = (c.get("extra") or {}).get("domain") or ""
    variant = (c.get("extra") or {}).get("variant") or "classic"
    out: List[Dict[str, Any]] = []
    seen: set = set()
    for term in terms[:3]:
        for page in range(_EIGHTFOLD_PAGES_PER_TERM):
            start = page * _EIGHTFOLD_PAGE
            if variant == "pcsx":
                r = _SESSION.get(
                    f"https://{host}/api/pcsx/search",
                    params={"domain": domain, "query": term,
                            "location": "United States", "start": start},
                    timeout=REQUEST_TIMEOUT)
                r.raise_for_status()
                positions = ((r.json() or {}).get("data") or {}).get("positions") or []
            else:
                r = _SESSION.get(
                    f"https://{host}/api/apply/v2/jobs",
                    params={"domain": domain, "query": term,
                            "location": "United States", "start": start,
                            "num": _EIGHTFOLD_PAGE},
                    timeout=REQUEST_TIMEOUT)
                r.raise_for_status()
                positions = (r.json() or {}).get("positions") or []
            for j in positions:
                jid = j.get("id")
                if jid in seen:
                    continue
                seen.add(jid)
                locs = j.get("locations") or ([j.get("location")] if j.get("location") else [])
                # Posting timestamps only — t_update/t_create are record-edit
                # times and made stale reqs look freshly posted.
                posted = j.get("postedTs") or j.get("creationTs")
                url = (j.get("canonicalPositionUrl")
                       or f"https://{host}/careers/job/{jid}?domain={domain}")
                out.append(_row(
                    c, jid, j.get("name") or "", url,
                    _epoch_to_iso(posted), "; ".join(str(x) for x in locs[:3])))
            if len(positions) < _EIGHTFOLD_PAGE:
                break
    return out


def _fetch_phenom(c: Dict[str, str], terms: List[str]) -> List[Dict[str, Any]]:
    host = c["host"]
    out: List[Dict[str, Any]] = []
    for term in terms[:3]:
        body = {
            "lang": "en_us", "deviceType": "desktop", "country": "us",
            "pageName": "search-results", "ddoKey": "refineSearch",
            "sortBy": "", "from": 0, "jobs": True, "counts": True,
            "all_fields": ["category", "country", "state", "city", "type"],
            "size": 20, "keywords": term, "global": True,
            # No server-side country filter: tenants disagree on the value
            # ("United States" vs "United States of America") and a miss
            # silently returns 0 hits. _keep_us filters on the row's own
            # country field instead.
            "selected_fields": {},
            "locationData": {},
        }
        r = _SESSION.post(f"https://{host}/widgets", json=body,
                          timeout=REQUEST_TIMEOUT)
        r.raise_for_status()
        data = ((r.json() or {}).get("refineSearch") or {}).get("data") or {}
        for j in data.get("jobs") or []:
            loc = j.get("cityState") or ", ".join(
                x for x in [j.get("city"), j.get("state")] if x)
            jid = j.get("jobSeqNo") or j.get("jobId") or j.get("reqId")
            url = (j.get("applyUrl") or j.get("externalApply")
                   or f"https://{host}/us/en/job/{jid}")
            out.append(_row(
                c, jid, j.get("title") or "", url,
                _iso(j.get("postedDate") or j.get("dateCreated")), loc,
                description=_html_to_text(j.get("descriptionTeaser") or "")[:2000],
                country=str(j.get("country") or "")))
    return out


def _fetch_orc(c: Dict[str, str], terms: List[str]) -> List[Dict[str, Any]]:
    """Oracle Recruiting Cloud (ORC) — public CandidateExperience JSON API.

    Config-driven: any company hosting on {host}/hcmRestApi (JPMorgan Chase,
    Oracle itself, ...). ONE request per company — the `finder` DSL carries
    the keyword server-side, so no per-term fan-in. Every posting on an ORC
    host belongs to that company, so no employer filtering is needed.
    Endpoint verified live 2026-07-17 (jpmc.fa.oraclecloud.com,
    eeho.fa.us2.oraclecloud.com).
    """
    host = c["host"]
    site = (c.get("extra") or {}).get("site_number") or "CX_1"
    kw = " ".join(t.strip() for t in terms if t.strip()).strip()
    finder = f"findReqs;siteNumber={site}"
    if kw:
        finder += f",keyword={kw}"
    finder += ",limit=25,sortBy=POSTING_DATES_DESC"
    try:
        r = _SESSION.get(
            f"https://{host}/hcmRestApi/resources/latest/recruitingCEJobRequisitions",
            params={"onlyData": "true",
                    "expand": "requisitionList.secondaryLocations",
                    "finder": finder},
            timeout=HEAVY_REQUEST_TIMEOUT)
        r.raise_for_status()
        items = (r.json() or {}).get("items") or []
        if not items:
            return []
        out: List[Dict[str, Any]] = []
        for j in items[0].get("requisitionList") or []:
            if not isinstance(j, dict):
                continue
            desc = " ".join(x for x in [
                j.get("ShortDescriptionStr") or "",
                j.get("ExternalQualificationsStr") or "",
                j.get("ExternalResponsibilitiesStr") or ""] if x)
            out.append(_row(
                c, j.get("Id"), j.get("Title") or "",
                f"https://{host}/hcmUI/CandidateExperience/en/sites/{site}"
                f"/job/{j.get('Id')}",
                _iso(j.get("PostedDate")),
                j.get("PrimaryLocation") or "",
                description=_html_to_text(desc)[:5000],
                country=str(j.get("PrimaryLocationCountry") or "")))
        logger.info("orc: %s returned %d rows (total=%s)",
                    c.get("slug"), len(out), items[0].get("TotalJobsCount"))
        return out
    except Exception as e:
        logger.warning("orc: %s fetch failed: %s", c.get("slug"), type(e).__name__)
        return []


def _fetch_uber(c: Dict[str, str], terms: List[str]) -> List[Dict[str, Any]]:
    """Uber's first-party careers search API (single company, no config).

    POST loadSearchJobsResults with the literal csrf token "x" (accepted
    anonymously). Endpoint verified live 2026-07-17.
    """
    query = " ".join(t.strip() for t in terms if t.strip()).strip()
    body = {"params": {"query": query, "location": []}, "page": 0, "limit": 25}
    try:
        r = _SESSION.post(
            "https://www.uber.com/api/loadSearchJobsResults?localeCode=en",
            json=body, headers={"x-csrf-token": "x"},
            timeout=HEAVY_REQUEST_TIMEOUT)
        r.raise_for_status()
        data = (r.json() or {}).get("data") or {}
        results = data.get("results") or []
        total = data.get("totalResults")
        if isinstance(total, dict):   # API returns {"low": N} on some builds
            total = total.get("low")
        out: List[Dict[str, Any]] = []
        for j in results:
            if not isinstance(j, dict):
                continue
            locs = [x for x in (j.get("allLocations") or []) if isinstance(x, dict)]
            loc0 = locs[0] if locs else (
                j.get("location") if isinstance(j.get("location"), dict) else {})
            location = ", ".join(
                str(x) for x in [loc0.get("city"), loc0.get("region"),
                                 loc0.get("countryName")] if x)
            if not location and isinstance(j.get("location"), str):
                location = j["location"]
            title = str(j.get("title") or "")
            desc = _html_to_text(str(j.get("description") or ""))
            out.append(_row(
                c, j.get("id"), title,
                f"https://www.uber.com/global/en/careers/list/{j.get('id')}/",
                # creationDate only: updatedDate is an edit timestamp.
                _iso(j.get("creationDate")),
                location,
                description=desc[:5000],
                is_remote=bool(_REMOTE_RE.search(title + " " + desc)) or None,
                country=str(loc0.get("country") or "")))
        logger.info("uber: %s returned %d rows (total=%s)",
                    c.get("slug"), len(out), total)
        return out
    except Exception as e:
        logger.warning("uber: fetch failed: %s", type(e).__name__)
        return []


def _fetch_radancy(c: Dict[str, str], terms: List[str]) -> List[Dict[str, Any]]:
    """Radancy Talent Acquisition Cloud, on the employer's own hostname.

    Deliberately thin. The protocol lives in
    `services.ats_providers.radancy.RadancyProvider` - the one place the
    background crawl also reads it from - and this adapter only translates the
    interactive path's (company dict, terms) call into it and the result back
    into `_row`. Writing the HTTP a second time here is how the two Workday
    tenant lists in this repo drifted apart, and there is no reason to repeat
    it for a vendor added after the provider registry existed.
    """
    host = str(c.get("host") or "").strip().lower()
    if not host:
        return []
    from services.ats_providers import registry as ats_registry
    from services.ats_providers.base import Endpoint
    from services.ats_providers.http import simple_context

    provider = ats_registry.get("radancy")
    if provider is None:                       # pragma: no cover - defensive
        return []
    endpoint = Endpoint(vendor="radancy", tenant=str(c.get("slug") or host),
                        site="", host=host)
    out: List[Dict[str, Any]] = []
    seen: set = set()
    for term in (terms or [""])[:3]:
        ctx = simple_context(budget_seconds=REQUEST_TIMEOUT * 3,
                             options={"keyword": term})
        try:
            for job in provider.list_jobs(endpoint, ctx):
                if job.source_job_id in seen:
                    continue
                seen.add(job.source_job_id)
                out.append(_row(c, job.source_job_id, job.title, job.apply_url,
                                job.posted_at, job.location))
        except Exception:                      # one vendor must not fail a tab
            continue
    return out


def _fetch_via_provider(c: Dict[str, str], terms: List[str], vendor: str, *,
                        keyword_option: str = "keyword",
                        cap: int = 400) -> List[Dict[str, Any]]:
    """Run a REGISTERED provider for the interactive tab.

    Deliberately thin, for the reason `_fetch_radancy` gives: the protocol
    belongs in `services.ats_providers` — the one place the background crawl
    also reads it from — and writing the HTTP a second time here is how the two
    Workday tenant lists in this repo drifted apart. This adapter only
    translates the tab's `(company dict, terms)` call into the provider and the
    provider's `RawJob`s back into `_row`.
    """
    from services.ats_providers import registry as ats_registry
    from services.ats_providers.base import Endpoint
    from services.ats_providers.http import simple_context

    provider = ats_registry.get(vendor)
    if provider is None:                       # pragma: no cover - defensive
        return []
    host = str(c.get("host") or "").strip().lower()
    endpoint = Endpoint(vendor=vendor, tenant=str(c.get("slug") or vendor),
                        site=str(c.get("site") or ""), host=host,
                        extra=dict(c.get("extra") or {}))
    out: List[Dict[str, Any]] = []
    seen: set = set()
    for term in (terms or [""])[:2]:
        ctx = simple_context(budget_seconds=HEAVY_REQUEST_TIMEOUT * 3,
                             options={keyword_option: term})
        try:
            for job in provider.list_jobs(endpoint, ctx):
                if job.source_job_id in seen:
                    continue
                seen.add(job.source_job_id)
                out.append(_row(c, job.source_job_id, job.title, job.apply_url,
                                job.posted_at, job.location,
                                description=(job.description or "")[:5000],
                                country=job.country, is_remote=job.remote))
                if len(out) >= cap:
                    return out
        except Exception:                      # one vendor must not fail a tab
            continue
    return out


