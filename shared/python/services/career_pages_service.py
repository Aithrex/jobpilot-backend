# ----------------------------------------------------------------------
# Relevance keep-filter (boards return EVERYTHING; Workday searched for us)
# ----------------------------------------------------------------------

# Role nouns worth keeping even without a full term match — boards return
# their ENTIRE openings list (Workday searched for us), so recall depends on
# this net. "Backend Engineer" / "Site Reliability Engineer" / "Infrastructure
# Engineer" must survive a "devops engineer, software developer" term set.
_ROLE_NOUN_RE = re.compile(
    r"engineer|developer|scientist|architect|devops|\bsre\b|programmer",
    re.IGNORECASE)


def _keep_relevant(jobs: List[Dict[str, Any]], term_res: List[re.Pattern],
                   skill_res: List[re.Pattern],
                   extra_role_re: Optional[re.Pattern] = None) -> List[Dict[str, Any]]:
    """Keep rows a Workday CXS search WOULD have retrieved, tiered:
      0 - a query term matches the title (best)
      1 - the title carries a role noun (the built-in engineering net UNION the
          user's own profession nouns via ``extra_role_re`` — so a nurse also
          recalls 'Charge Nurse' rows), or the description mentions >=2 distinct
          resume skills (the differently-titled-but-matching-skills recall path)
    The tier drives the per-company cap so term matches never lose their
    slot to generic engineer rows."""
    out = []
    for j in jobs:
        title = j["title"].lower()
        hits = [rx.pattern for rx in term_res if rx.search(title)]
        if hits:
            j["matched_terms"] = hits[:3]
            j["_tier"] = 0
            out.append(j)
            continue
        if _ROLE_NOUN_RE.search(title) or (extra_role_re and extra_role_re.search(title)):
            j["matched_terms"] = []
            j["_tier"] = 1
            out.append(j)
            continue
        # Include inline board metadata so a description-less row (SmartRecruiters
        # / Workable) can still be recalled by skills its department/function names.
        desc = ((j.get("description") or "") + " " + (j.get("_meta") or "")).lower()
        if desc.strip() and sum(1 for rx in skill_res if rx.search(desc)) >= 2:
            j["matched_terms"] = []
            j["_tier"] = 1
            out.append(j)
    return out


# ----------------------------------------------------------------------
# Detail enrichment for rows that arrived without descriptions
# (greenhouse content, smartrecruiters ad, workable v2 job)
# ----------------------------------------------------------------------

def _detail_one(job: Dict[str, Any]) -> bool:
    ats, slug = job.get("ats"), job.get("tenant")
    rid = str(job["job_id"]).rsplit(":", 1)[-1]
    try:
        if ats == "greenhouse":
            r = _SESSION.get(
                f"https://boards-api.greenhouse.io/v1/boards/{slug}/jobs/{rid}",
                timeout=DETAIL_TIMEOUT)
            if r.status_code != 200:
                return False
            job["description"] = _html_to_text((r.json() or {}).get("content") or "")[:5000]
            return bool(job["description"])
        if ats == "smartrecruiters":
            r = _SESSION.get(
                f"https://api.smartrecruiters.com/v1/companies/{slug}/postings/{rid}",
                timeout=DETAIL_TIMEOUT)
            if r.status_code != 200:
                return False
            ad = ((r.json() or {}).get("jobAd") or {}).get("sections") or {}
            text = " ".join(
                _html_to_text((ad.get(k) or {}).get("text") or "")
                for k in ("jobDescription", "qualifications", "additionalInformation"))
            job["description"] = text.strip()[:5000]
            return bool(job["description"])
        if ats == "workable":
            r = _SESSION.get(
                f"https://apply.workable.com/api/v2/accounts/{slug}/jobs/{rid}",
                timeout=DETAIL_TIMEOUT)
            if r.status_code != 200:
                return False
            data = r.json() or {}
            job["description"] = _html_to_text(
                (data.get("description") or "") + " " +
                (data.get("requirements") or ""))[:5000]
            return bool(job["description"])
        if ats == "eightfold":
            ent = next((e for e in ENTERPRISE_CATALOG if e["slug"] == slug), None)
            if not ent or (ent.get("extra") or {}).get("variant") == "pcsx":
                return False  # no anonymous detail JSON on PCSX tenants
            r = _SESSION.get(
                f"https://{ent['host']}/api/apply/v2/jobs/{rid}",
                params={"domain": (ent.get("extra") or {}).get("domain") or ""},
                timeout=DETAIL_TIMEOUT)
            if r.status_code != 200:
                return False
            job["description"] = _html_to_text(
                (r.json() or {}).get("job_description") or "")[:5000]
            return bool(job["description"])
    except (requests.RequestException, ValueError):
        return False
    return False


def _enrich_details(jobs: List[Dict[str, Any]]) -> int:
    need = [j for j in jobs if not j.get("description")
            and j.get("ats") in ("greenhouse", "smartrecruiters", "workable",
                                 "eightfold")]
    if not need:
        return 0
    done = 0
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as pool:
        for ok in pool.map(_detail_one, need):
            done += 1 if ok else 0
    return done


