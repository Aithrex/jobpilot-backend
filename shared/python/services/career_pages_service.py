def _get_cache_collection():
    try:
        from utils.db_connect import DBConnect
        db = DBConnect().get_db()
        coll = db[CACHE_COLLECTION]
        try:
            # Named explicitly so scripts/migrate_indexes.py can re-assert the
            # same specs on a fresh DB without a name conflict.
            coll.create_index("cached_at", expireAfterSeconds=CACHE_TTL_SECONDS,
                              name="career_pages_cache_ttl")
            coll.create_index("cache_key")
        except Exception:
            pass
        return coll
    except Exception as e:
        logger.warning("career-pages: cache unavailable: %s", e)
        return None


def _cache_key(rows: List[Dict[str, str]], terms: List[str], us_only: bool) -> str:
    basis = json.dumps({
        "v": RESULT_SCHEMA_VERSION,
        "slugs": sorted(f"{r['ats']}:{r['slug']}" for r in rows),
        "terms": sorted(t.lower() for t in terms),
        "us": bool(us_only),
    }, sort_keys=True)
    return hashlib.sha256(basis.encode()).hexdigest()


def _read_cache(coll, key: str) -> Optional[List[Dict[str, Any]]]:
    if coll is None:
        return None
    try:
        doc = coll.find_one({"cache_key": key})
        if not doc:
            return None
        age = (datetime.now(timezone.utc)
               - doc["cached_at"].replace(tzinfo=timezone.utc)).total_seconds()
        if age > CACHE_FRESH_SECONDS:
            return None
        return doc.get("jobs") or []
    except Exception:
        return None


def _write_cache(coll, key: str, jobs: List[Dict[str, Any]]) -> None:
    if coll is None:
        return
    try:
        coll.update_one(
            {"cache_key": key},
            {"$set": {"cache_key": key, "jobs": jobs,
                      "cached_at": datetime.now(timezone.utc)}},
            upsert=True)
    except Exception as e:
        logger.warning("career-pages: cache write failed: %s", e)


def _apply_career_sponsorship(jobs: List[Dict[str, Any]]) -> None:
    """Override company-tier sponsorship with the CAREER catalog's data.

    _attach_sponsorship looks tenants up in the WORKDAY tier table, which
    career slugs never (correctly) hit — everything lands "unknown". The
    career research (FY2024/25 USCIS data keyed by career slug) is
    authoritative here; JD-level refusals always stand.
    """
    try:
        from services.h1b_sponsor_data_careers import CAREER_H1B_SPONSORS
    except Exception:  # pragma: no cover
        return
    # Enterprise-platform companies aren't in the generated module (it is
    # keyed to the board-ATS catalog) — approximate FY2025 USCIS volumes.
    enterprise_tiers: Dict[str, Tuple[str, int]] = {
        "amazon": ("high", 9000), "microsoft": ("high", 5000),
        "netflix": ("medium", 250), "johndeere": ("medium", 150),
        "whirlpool": ("low", 40), "usbank": ("medium", 150),
        "united": ("medium", 90), "southwest": ("low", 30),
        "lilly": ("medium", 200), "merck": ("medium", 300),
        "lowes": ("medium", 120), "ecolab": ("medium", 90),
        "landolakes": ("low", 20),
    }
    for job in jobs:
        if job.get("sponsorship") == "refused":
            continue
        info = (CAREER_H1B_SPONSORS.get(job.get("tenant") or "")
                or enterprise_tiers.get(job.get("tenant") or ""))
        if not info:
            continue
        tier, approvals = info
        # ESTIMATE from a curated employer tier list — NOT live per-employer USCIS
        # data. Label it so the "honest sponsorship" promise is never overstated.
        if tier in ("high", "medium"):
            job["sponsorship"] = "likely"
            job["h1b_sponsor"] = True
            job["sponsor_source"] = "estimate"
            job["sponsor_note"] = (
                f"Est.: {job['company']} historically files ~{approvals:,} H-1Bs/yr")
        elif tier == "low":
            job["sponsorship"] = "rare"
            job["sponsor_source"] = "estimate"
            job["sponsor_note"] = f"Est.: {job['company']} files few H-1Bs (~{approvals}/yr)"


