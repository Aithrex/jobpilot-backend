def _fetch_greenhouse(c: Dict[str, str]) -> List[Dict[str, Any]]:
    r = _SESSION.get(
        f"https://boards-api.greenhouse.io/v1/boards/{c['slug']}/jobs?content=false",
        timeout=REQUEST_TIMEOUT)
    r.raise_for_status()
    out = []
    for j in (r.json() or {}).get("jobs") or []:
        # first_published ONLY. updated_at is an edit timestamp, not a posting
        # date: falling back to it re-dated months-old reqs as "new" (and
        # Greenhouse is over half the catalog, so it was the single biggest
        # source of fake freshness). No first_published => the date is
        # UNKNOWN, and an unknown date is correctly dropped downstream.
        date = j.get("first_published") or ""
        out.append(_row(
            c, j.get("id"), j.get("title") or "", j.get("absolute_url") or "",
            _iso(date), ((j.get("location") or {}).get("name")) or ""))
    return out


def _fetch_lever(c: Dict[str, str]) -> List[Dict[str, Any]]:
    r = _SESSION.get(
        f"https://api.lever.co/v0/postings/{c['slug']}?mode=json",
        timeout=REQUEST_TIMEOUT)
    r.raise_for_status()
    data = r.json()
    out = []
    for j in data if isinstance(data, list) else []:
        cats = j.get("categories") or {}
        wp = str(j.get("workplaceType") or "").lower()
        out.append(_row(
            c, j.get("id"), j.get("text") or "", j.get("hostedUrl") or "",
            _ms_to_iso(j.get("createdAt")), cats.get("location") or "",
            description=str(j.get("descriptionPlain") or "")[:5000],
            is_remote=(wp == "remote") or None,
            country=str(j.get("country") or "")))
    return out


def _fetch_ashby(c: Dict[str, str]) -> List[Dict[str, Any]]:
    # Ashby's posting API is GET-only (POST returns 401).
    r = _SESSION.get(
        f"https://api.ashbyhq.com/posting-api/job-board/{c['slug']}",
        timeout=REQUEST_TIMEOUT)
    r.raise_for_status()
    out = []
    for j in (r.json() or {}).get("jobs") or []:
        if j.get("isListed") is False:
            continue
        loc = j.get("location") or ""
        secondary = ", ".join(
            (s.get("location") or "") for s in j.get("secondaryLocations") or [])
        address = (((j.get("address") or {}).get("postalAddress") or {})
                   .get("addressCountry") or "")
        out.append(_row(
            c, j.get("id"), j.get("title") or "",
            j.get("jobUrl") or j.get("applyUrl") or "",
            _iso(j.get("publishedAt")),
            loc + ((" · " + secondary) if secondary else ""),
            description=_html_to_text(j.get("descriptionHtml") or "")[:5000],
            is_remote=j.get("isRemote"),
            country=address))
    return out


def _fetch_smartrecruiters(c: Dict[str, str]) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    offset = 0
    for _page in range(2):  # 100/page; 200 newest is plenty for a 30d window
        # country=us server-side: giant multinationals (AccorHotels: 5,800+
        # postings) would otherwise bury the US slice beyond our 2 pages.
        r = _SESSION.get(
            f"https://api.smartrecruiters.com/v1/companies/{c['slug']}/postings"
            f"?limit=100&offset={offset}&country=us", timeout=REQUEST_TIMEOUT)
        r.raise_for_status()
        data = r.json() or {}
        content = data.get("content") or []
        for j in content:
            loc = j.get("location") or {}
            city = ", ".join(x for x in [loc.get("city"), loc.get("region")] if x)
            # SmartRecruiters ships function/department/experience/industry
            # labels inline (no description in the list response) — keep them.
            meta = " · ".join(x for x in (
                (j.get("function") or {}).get("label"),
                (j.get("department") or {}).get("label"),
                (j.get("experienceLevel") or {}).get("label"),
                (j.get("industry") or {}).get("label")) if x)
            out.append(_row(
                c, j.get("id"), j.get("name") or "",
                f"https://jobs.smartrecruiters.com/{c['slug']}/{j.get('id')}",
                _iso(j.get("releasedDate")), city,
                is_remote=bool(loc.get("remote")) or None,
                country=str(loc.get("country") or ""), meta=meta,
                exp=(j.get("experienceLevel") or {}).get("label") or ""))
        offset += len(content)
        if len(content) < 100:
            break
    return out


