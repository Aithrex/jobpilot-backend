"""Curated tech-employer seed for the company registry.

Why this file exists
--------------------
`companies` was seeded from SEC EDGAR (`signals.edgar`), so it holds every
PUBLIC filer and almost no private one. Measured 2026-09-02 against live
`aspirely_db`: MongoDB, Datadog, Snowflake, Nvidia, Coinbase, Reddit, Twilio,
Okta, CrowdStrike, DoorDash, Robinhood, GitLab and Elastic were all present -
every one of them public - while Databricks, Stripe, Confluent, Notion,
Discord, Anthropic, OpenAI, Scale AI, Rippling, Plaid, Ramp, Instacart and
Vercel were absent entirely. Only 796 of 82,492 rows carried
`signals.software`.

That is the whole reason the feed skews to Workday retail and healthcare while
a tech user's shortlist (the private, venture-backed cohort) is missing: a
company that is not in `companies` is never probed, so its board is never
found, so its postings can never be ingested.

What a row here is, and is NOT
------------------------------
A row is a CANDIDATE to probe, nothing more. It asserts only that the employer
exists and hires in tech. It does NOT assert which ATS they use - that is
discovered and owner-verified by `scripts/probe_software_company_boards.py`,
which rejects a board whose `board_owner` names a different company. So a wrong
domain here costs a missed board, never a mis-attributed one.

`domain` feeds slug-candidate generation only. `category` is descriptive.
"""
