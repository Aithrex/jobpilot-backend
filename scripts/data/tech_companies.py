def as_records(source: str = "curated-tech-seed") -> List[Dict[str, object]]:
    """`company_registry_service.upsert_company` records.

    `signals.software` is set EXPLICITLY rather than left to
    `signals_for_company`, which derives from SIC (absent for a private
    company) and otherwise falls back to a name regex that "Databricks" and
    "Stripe" do not match. The signal is what
    `probe_software_company_boards.py --signal software` sweeps on, so a row
    without it is seeded and then never probed.
    """
    out: List[Dict[str, object]] = []
    for name, domain, category in TECH_COMPANIES:
        out.append({
            "name": name,
            "domain": domain,
            "signals": {"software": True},
            "sources": [source],
            "tech_category": category,
        })
    return out
